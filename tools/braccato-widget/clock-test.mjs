import assert from 'node:assert/strict';
import { PlaybackClock } from './clock.ts';
const clock = new PlaybackClock();
clock.sample(10,true,1,0);
assert.equal(clock.read(100),10.1);
clock.sample(10.08,true,1,100);
assert.equal(clock.read(100),10.1,'a delayed host sample does not jerk the displayed clock backwards');
assert.ok(clock.read(170)>10.1,'playback continues while correction settles');
assert.equal(clock.read(240),10.22,'ordinary drift converges');
clock.sample(40,true,1,250);
assert.equal(clock.read(250),40,'seeking snaps immediately');
clock.sample(40.1,false,1,350);
assert.equal(clock.read(900),40.1,'paused playback stays still');
clock.sample(40.1,true,2,900);
assert.ok(Math.abs(clock.read(1000)-40.3)<1e-9,'rate changes apply immediately');
assert.equal(clock.read(5000),42.1,'missing samples cannot run away indefinitely');
clock.sample(NaN,true,1,5000);
assert.ok(Number.isFinite(clock.read(5000)),'malformed samples do not poison the clock');
const lag = new PlaybackClock();
lag.sample(10,true,1,0);
lag.sample(10.01,true,1,240);
assert.ok(lag.read(260) >= lag.read(240),'large ordinary jitter cannot reverse playback');
console.log('PASS: clock jitter smoothing, seeking, pause, rate changes, stale samples and invalid input');
